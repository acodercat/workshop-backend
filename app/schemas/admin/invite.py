"""Request / response models for invite codes and their redemptions."""

from datetime import datetime

from pydantic import BaseModel, Field

from app.models.invite_code import InviteCodeOrigin
from app.schemas.admin.fields import Reason


class InviteCodeResponse(BaseModel):
    """One invite code.

    ``max_uses`` is ``None`` for unlimited — the column's own meaning,
    kept rather than flattened to a sentinel number.
    """

    id: int
    code: str
    origin: InviteCodeOrigin
    owner_user_id: int | None
    owner_username: str | None
    max_uses: int | None
    used_count: int
    enabled: bool
    note: str | None
    expires_at: datetime | None
    created_at: datetime


class InviteCodeCreate(BaseModel):
    """Issue an operator code.

    Always ``SYSTEM`` origin — ``REFERRAL`` codes belong to a user and
    are minted by registration, so letting the console create one would
    forge a referral relationship. The code itself is generated by the
    service; an operator picking one would eventually pick a guessable
    one.
    """

    max_uses: int | None = Field(default=1, ge=1, le=10_000)
    note: str | None = Field(default=None, max_length=500)
    reason: Reason


class InviteRedemptionResponse(BaseModel):
    """One redemption — who joined on whose code.

    ``referrer_*`` is ``None`` for ``SYSTEM`` codes: nobody referred
    them, which is exactly why those redemptions pay no commission.
    """

    id: int
    code: str
    origin: InviteCodeOrigin
    invitee_user_id: int
    invitee_username: str
    referrer_user_id: int | None
    referrer_username: str | None
    created_at: datetime
